//go:build windows

package main

import (
	"os"
	"path/filepath"
)

const windowsDataDirName = "WorkBuddy2API"

// defaultConfigPath gives installed Windows builds a stable per-user data
// directory while keeping portable deployments backwards compatible. If a
// config.json is next to the executable/working directory, that file wins.
func defaultConfigPath() string {
	if _, err := os.Stat("config.json"); err == nil {
		return "config.json"
	}
	if root := os.Getenv("LOCALAPPDATA"); root != "" {
		return filepath.Join(root, windowsDataDirName, "config.json")
	}
	return "config.json"
}

// resolveManagedConfigPaths makes the relative paths generated by Default
// follow the managed config file instead of the caller's current directory.
// Explicit -config files and portable current-directory installs retain their
// historical semantics.
func resolveManagedConfigPaths(c *Config, path string) {
	root := os.Getenv("LOCALAPPDATA")
	if root == "" || filepath.Clean(path) != filepath.Clean(filepath.Join(root, windowsDataDirName, "config.json")) {
		return
	}
	base := filepath.Dir(path)
	resolve := func(value string) string {
		if value == "" || filepath.IsAbs(value) {
			return value
		}
		return filepath.Join(base, value)
	}
	c.AuthDir = resolve(c.AuthDir)
	c.StateFile = resolve(c.StateFile)
	c.Upstream.DeviceTokenFile = resolve(c.Upstream.DeviceTokenFile)
	c.Upstream.DumpDir = resolve(c.Upstream.DumpDir)
	c.Prompt.File = resolve(c.Prompt.File)
	c.Admin.AuditFile = resolve(c.Admin.AuditFile)
}
